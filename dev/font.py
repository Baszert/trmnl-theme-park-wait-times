# Embeds the RCT2 font (Qimplef, CC BY-SA 3.0, via koaning/rct-css) into src/shared.liquid as a data URI.
import base64, re
b = base64.b64encode(open('dev/rct2.otf', 'rb').read()).decode()
block = '/* RCT2 font, generated by dev/font.py */\n  @font-face { font-family: "RCT2"; src: url(data:font/otf;base64,' + b + ') format("opentype"); }\n  /* /RCT2 font */'
p = 'src/shared.liquid'; s = open(p).read()
s = re.sub(r'/\* RCT2 font, generated.*?/\* /RCT2 font \*/', lambda m: block, s, flags=re.S)
open(p, 'w').write(s); print('font bytes', len(b))
